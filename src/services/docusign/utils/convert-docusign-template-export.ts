/**
 * Converts a DocuSign template JSON export into a platform coordinate layout.
 *
 * Usage (from repo root):
 *   npx ts-node in-house-crm-be/src/services/docusign/utils/convert-docusign-template-export.ts \
 *     --in ./Contract.json --key contract --out ./contract.layout.json
 */

import * as fs from 'fs';
import * as path from 'path';

export type DocumentLayoutPlacement = {
  id: string;
  type: 'text' | 'date' | 'signature' | 'initial' | 'attachment';
  variable?: string;
  slot?: string;
  /** CRM signer role when type is signature | initial */
  signerRole?: string;
  /** Logical party for dynamic owner routing (owner | owner2 | client | guarantor). */
  /** primary = merchant/client/owner1/guarantor1 (same person); secondary = owner2/guarantor2 */
  signerParty?: 'primary' | 'secondary' | 'owner' | 'owner2' | 'client' | 'guarantor' | 'guarantor2';
  /** e.g. owners >= 2 — evaluated at envelope build time */
  when?: string;
  documentId: string;
  pageNumber: string;
  x: string;
  y: string;
  width?: string;
  height?: string;
  optional?: boolean;
  sourceTabLabel?: string;
  /** When true, prefill tab is locked so signers cannot edit. */
  lockedForSigner?: boolean;
  /** When true, tab is left blank at send so the signer fills it during signing (never locked or flattened). */
  fillAtSigning?: boolean;
};

export type DocumentLayout = {
  layoutVersion: number;
  key: string;
  name: string;
  description?: string;
  /** When true, do not mirror primary initials for owner 2 (standalone ACH send). */
  skipOwner2InitialMirror?: boolean;
  legacyDocuSignTemplateId?: string;
  pdf?: {
    source: 'contractTemplate' | 'boldSignTemplate';
    fileName?: string;
  };
  document: {
    documentId: string;
    originalFileName?: string;
    pageCount?: number;
  };
  signers: Array<{
    roleName: string;
    routingOrder: number;
    legacyRecipientId?: string;
  }>;
  variables: string[];
  placements: DocumentLayoutPlacement[];
};

const TAB_TYPE_MAP: Record<string, DocumentLayoutPlacement['type']> = {
  signhere: 'signature',
  signhereoptional: 'signature',
  initialhere: 'initial',
  initialhereoptional: 'initial',
  datesigned: 'date',
  text: 'text',
};

function normalizeTabType(raw: string | undefined, key: string): DocumentLayoutPlacement['type'] {
  const t = String(raw || key || '')
    .toLowerCase()
    .replace(/tabs?$/i, '');
  return TAB_TYPE_MAP[t] || (t as DocumentLayoutPlacement['type']);
}

function isAutoGeneratedLabel(label: string): boolean {
  return /^(Signature|Initial|Date Signed|Attachment) [0-9a-f-]{36}$/i.test(label);
}

function slotFromTab(
  tabType: DocumentLayoutPlacement['type'],
  pageNumber: string,
  x: string,
  y: string,
  label: string,
): string {
  if (label && !isAutoGeneratedLabel(label)) {
    return label.replace(/\s+/g, '_').toLowerCase();
  }
  return `${tabType}_p${pageNumber}_${x}_${y}`;
}

export function convertDocuSignTemplateExport(
  exportJson: string | Record<string, unknown>,
  meta: {
    key: string;
    name?: string;
    description?: string;
    pdfSource?: 'contractTemplate' | 'boldSignTemplate';
    pdfFileName?: string;
  },
): DocumentLayout {
  const j =
    typeof exportJson === 'string'
      ? (JSON.parse(exportJson) as Record<string, unknown>)
      : exportJson;
  const doc = (j.documents as Array<Record<string, unknown>> | undefined)?.[0];
  const placements: DocumentLayoutPlacement[] = [];
  let seq = 0;

  const signers = ((j.recipients as Record<string, unknown>)?.signers ||
    []) as Array<Record<string, unknown>>;

  for (const signer of signers) {
    const roleName = String(signer.roleName || 'Signer');
    const tabs = (signer.tabs || {}) as Record<string, unknown>;

    for (const [tabKey, rawArr] of Object.entries(tabs)) {
      if (!Array.isArray(rawArr)) continue;
      for (const raw of rawArr) {
        const t = raw as Record<string, unknown>;
        const tabType = normalizeTabType(String(t.tabType || ''), tabKey);
        const label = String(t.tabLabel || t.name || '').trim();
        const optional = t.optional === 'true' || t.required === 'false';
        const pageNumber = String(t.pageNumber || '1');
        const x = String(t.xPosition ?? '');
        const y = String(t.yPosition ?? '');
        if (!x || !y) continue;

        const base = {
          documentId: String(t.documentId || doc?.documentId || '1'),
          pageNumber,
          x,
          y,
          ...(t.width ? { width: String(t.width) } : {}),
          ...(t.height ? { height: String(t.height) } : {}),
          signerRole: roleName,
          optional,
          ...(label ? { sourceTabLabel: label } : {}),
        };

        if (tabType === 'text') {
          const variable = label && !isAutoGeneratedLabel(label) ? label : undefined;
          if (!variable) continue;
          placements.push({
            id: `p${++seq}`,
            type: 'text',
            variable,
            ...base,
          });
          continue;
        }

        if (tabType === 'date') {
          const variable =
            label && !isAutoGeneratedLabel(label) ? label : 'signature_date';
          placements.push({
            id: `p${++seq}`,
            type: 'date',
            variable,
            slot: slotFromTab('date', pageNumber, x, y, label),
            ...base,
          });
          continue;
        }

        if (tabType === 'signature' || tabType === 'initial') {
          placements.push({
            id: `p${++seq}`,
            type: tabType,
            slot: slotFromTab(tabType, pageNumber, x, y, label),
            ...base,
          });
        }
      }
    }
  }

  const variables = [
    ...new Set(
      placements
        .map((p) => p.variable)
        .filter((v): v is string => Boolean(v)),
    ),
  ].sort();

  return {
    layoutVersion: 1,
    key: meta.key,
    name: String(j.name || meta.name || meta.key),
    description: meta.description,
    legacyDocuSignTemplateId: j.templateId ? String(j.templateId) : undefined,
    ...(meta.pdfSource
      ? {
          pdf: {
            source: meta.pdfSource,
            fileName: meta.pdfFileName,
          },
        }
      : {}),
    document: {
      documentId: String(doc?.documentId || '1'),
      originalFileName: doc?.name ? String(doc.name) : meta.pdfFileName,
      pageCount: doc?.pageCount ? Number(doc.pageCount) : undefined,
    },
    signers: signers.map((s) => ({
      roleName: String(s.roleName || 'Signer'),
      routingOrder: Number(s.routingOrder || 1),
      legacyRecipientId: s.recipientId ? String(s.recipientId) : undefined,
    })),
    variables,
    placements,
  };
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const getArg = (flag: string) => {
    const i = args.indexOf(flag);
    return i >= 0 ? args[i + 1] : undefined;
  };
  const input = getArg('--in');
  const key = getArg('--key');
  const output = getArg('--out');
  if (!input || !key || !output) {
    console.error(
      'Usage: convert-docusign-template-export --in <export.json> --key <layout_key> --out <layout.json>',
    );
    process.exit(1);
  }
  const layout = convertDocuSignTemplateExport(
    fs.readFileSync(path.resolve(input), 'utf8'),
    { key },
  );
  fs.mkdirSync(path.dirname(path.resolve(output)), { recursive: true });
  fs.writeFileSync(path.resolve(output), JSON.stringify(layout, null, 2));
  console.log(
    `Wrote ${layout.placements.length} placements (${layout.variables.length} variables) → ${output}`,
  );
}
